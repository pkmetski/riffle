    // --- Helpers ---

    // NOTE: 20/240 deliberately misses PanelMaskBinarizer's pre-binarized 0/255 fast path, so
    // fixtures re-run the full binarizer (texture pass erodes gutters ~2px vs the device mask —
    // the documented ±2px tolerance in the fidelity gate). Switching to 0/255 would make new
    // fixtures byte-exact BUT changes the effective input of every legacy fixture (#751-#780),
    // whose pins were validated under this loader and have no device ground truth to re-pin
    // against. Migrate only together with regenerated legacy fixtures.
    private val LIGHT: Byte = 240.toByte()
    private val DARK: Byte = 20.toByte()

    /**
     * Load a binarized-mask fixture (black=content, white=gutter) from the jvmTest classpath
     * and return it as a [PixelGrid]. Fixtures are stored as copyright-safe lossless PNGs per
     * ADR 0062 — black pixels map to [DARK] (content), any non-black pixel maps to [LIGHT] (gutter).
     *
     * Throws loudly if the resource is missing so the test fails rather than silently skipping.
     */
    private fun loadMaskFixture(resourcePath: String): PixelGrid {
        val stream = javaClass.classLoader.getResourceAsStream(resourcePath)
            ?: error("Fixture not found on classpath: $resourcePath — ensure the file exists under core/domain/src/jvmTest/resources/")
        val img = stream.use { javax.imageio.ImageIO.read(it) }
            ?: error("Could not decode image at $resourcePath")
        val w = img.width
        val h = img.height
        val luma = ByteArray(w * h)
        for (y in 0 until h) {
            for (x in 0 until w) {
                luma[y * w + x] = if ((img.getRGB(x, y) and 0xFFFFFF) == 0) DARK else LIGHT
            }
        }
        return PixelGrid(w, h, luma)
    }

    /**
     * Load a binarized-mask fixture (black=content, white=gutter) and return a [PanelBinaryMask]
     * directly, bypassing the full binarizer. Uses the same 0/255 fast-path mapping the device
     * uses for PanelMaskBinarizer: black pixels (0x000000) → 1 (content), any non-black pixel →
     * 0 (gutter). This gives byte-exact parity with the device's detection input and is required
     * when the 20/240 re-binarization path (used by [loadMaskFixture]) would run the texture pass
     * and produce a different detection outcome (see the loadMaskFixture note for why 20/240 is
     * kept as the default — migration to 0/255 requires regenerating all legacy fixtures).
     */
    private fun loadBinaryFixture(resourcePath: String): PanelBinaryMask {
        val stream = javaClass.classLoader.getResourceAsStream(resourcePath)
            ?: error("Fixture not found on classpath: $resourcePath — ensure the file exists under core/domain/src/jvmTest/resources/")
        val img = stream.use { javax.imageio.ImageIO.read(it) }
            ?: error("Could not decode image at $resourcePath")
        val w = img.width
        val h = img.height
        val data = ByteArray(w * h)
        for (y in 0 until h) {
            for (x in 0 until w) {
                data[y * w + x] = if ((img.getRGB(x, y) and 0xFFFFFF) == 0) 1 else 0
            }
        }
        return PanelBinaryMask(w, h, data)
    }

    /**
     * Load a raw (non-binarized) page image from the jvmTest classpath and convert it to a
     * luma [PixelGrid] using BT.601 coefficients. Use when the bug depends on real luma values
     * (e.g. background-estimation failures) that a binarized mask cannot reproduce.
     */
    private fun loadRawFixture(resourcePath: String): PixelGrid {
        val stream = javaClass.classLoader.getResourceAsStream(resourcePath)
            ?: error("Fixture not found on classpath: $resourcePath — ensure the file exists under core/domain/src/jvmTest/resources/")
        val img = stream.use { javax.imageio.ImageIO.read(it) }
            ?: error("Could not decode image at $resourcePath")
        val w = img.width
        val h = img.height
        val luma = ByteArray(w * h)
        for (y in 0 until h) {
            for (x in 0 until w) {
                val rgb = img.getRGB(x, y)
                val r = (rgb shr 16) and 0xFF
                val g = (rgb shr 8) and 0xFF
                val b = rgb and 0xFF
                luma[y * w + x] = (0.299 * r + 0.587 * g + 0.114 * b).toInt().coerceIn(0, 255).toByte()
            }
        }
        return PixelGrid(w, h, luma)
    }


