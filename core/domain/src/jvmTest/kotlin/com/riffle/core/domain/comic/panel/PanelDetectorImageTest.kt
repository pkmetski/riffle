/**
 * Panel-detector regression tests that run against real comic-page images.
 *
 * Every fixture is source-controlled in
 * `core/domain/src/jvmTest/resources/panel-detection-fixtures/` so tests always run on CI —
 * no conditional skips, no `.context/` paths.
 *
 * ## Fixture formats
 *
 * **Binarized mask PNG** (preferred, copyright-safe per ADR 0062): black pixels = content,
 * white pixels = gutter. Load with [loadMaskFixture], which maps black → DARK and white → LIGHT
 * and returns a [PixelGrid] ready for detection. Use this for images generated by the in-app
 * panel reporter (`PanelMaskEncoder`).
 *
 * **Raw page image**: a grayscale or colour scan. Load with [loadRawFixture] and pass the
 * returned [PixelGrid] to `detector.detect()`. Use only when the bug depends on real luma
 * values (e.g. background-estimation issues that a binarized mask can't reproduce).
 *
 * ## Adding a new test
 *  1. Download the binarized mask PNG from the issue's `panel-reports` branch URL and copy it
 *     to `core/domain/src/jvmTest/resources/panel-detection-fixtures/issue-<N>-<desc>.png`.
 *  2. Call [loadMaskFixture] (or [loadRawFixture] when luma fidelity is needed).
 *  3. Assert [PanelSource] and panel count; add geometry assertions where the issue specifies them.
 *  4. Run the test — it must fail RED before you touch [PanelDetector].
 *
 * Synthetic / geometry-only tests belong in [PanelDetectorTest].
 */
class PanelDetectorImageTest {

